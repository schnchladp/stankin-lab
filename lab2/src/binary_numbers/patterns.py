# src/binary_numbers/patterns.py
"""Регулярные выражения для двоичных чисел (лабораторная №2, вариант 26)

Предметная область: двоичное число - запись числа в двоичной системе
счисления. Допустимый вид записи задаётся грамматикой:

    <число>   ::= [<знак>] [<префикс>] <цифра> {<цифра>}
    <знак>    ::= "+" | "-"
    <префикс> ::= "0b" | "0B"
    <цифра>   ::= "0" | "1"

Ведущие нули допустимы ("0010"). Пробелы и разделители разрядов
("1 000", "1_000") не допускаются.
"""

import re

# Проверка: вся строка целиком должна быть двоичным числом
BINARY_FULL_RE = re.compile(
    r"""
    ^                      # начало строки
    (?P<sign>[+-])?        # необязательный знак
    (?P<prefix>0[bB])?     # необязательный префикс 0b / 0B
    (?P<digits>[01]+)      # одна или несколько двоичных цифр
    \Z                     # конец строки (в отличие от $, не пропускает
                           # завершающий перевод строки)
    """,
    re.VERBOSE,
)

# Поиск: двоичные числа как отдельные «слова» внутри произвольного текста
# Конструкции (?<!...) и (?!...) только проверяют соседние символы
# (lookaround) и сами в найденное совпадение не попадают
BINARY_SEARCH_RE = re.compile(
    r"""
    (?<!\w)                # слева не буква, не цифра и не «_»
    (?<!\d[.,])            # слева не дробный разделитель: 3.101, 3,101
    [+-]?                  # необязательный знак
    (?:0[bB])?             # необязательный префикс 0b / 0B
    [01]+                  # одна или несколько двоичных цифр
    (?!\w)                 # справа не буква, не цифра и не «_»
    (?![.,]\d)             # справа не дробный разделитель: 101.5, 101,5
    """,
    re.VERBOSE,
)
